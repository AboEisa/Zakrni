/**
 * Root theme — a clean, professional look on a calm neutral background.
 * Dark mode follows the app configuration (ThemeManager drives AppCompat night mode).
 */
@Composable
fun ZakrniTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    val colorScheme = if (darkTheme) DarkColors else LightColors

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as? Activity)?.window ?: return@SideEffect
            @Suppress("DEPRECATION")
            window.statusBarColor = colorScheme.background.toArgb()
            @Suppress("DEPRECATION")
            window.navigationBarColor = colorScheme.background.toArgb()
            val insets = WindowCompat.getInsetsController(window, view)
            insets.isAppearanceLightStatusBars = !darkTheme
            insets.isAppearanceLightNavigationBars = !darkTheme
        }
    }

    CompositionLocalProvider(LocalSpacing provides Spacing()) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = ZakrniTypography,
            shapes = ZakrniShapes,
        ) {
            Box(Modifier.fillMaxSize().background(appBackgroundBrush(darkTheme))) {
                content()
            }
        }
    }
}

/** Calm, very subtle background gradient (almost flat) for a premium, uncluttered feel. */
fun appBackgroundBrush(dark: Boolean): Brush = Brush.verticalGradient(
    if (dark) listOf(Color(0xFF0E1213), Color(0xFF11181A))
    else listOf(Color(0xFFFAFBFC), Color(0xFFF2F4F6)),
)

/** Clean (opaque) card/bar surface. */
val ColorScheme.glassSurface: Color get() = surface

/** Hairline border for cards/bars. */
val ColorScheme.glassBorder: Color get() = outlineVariant
